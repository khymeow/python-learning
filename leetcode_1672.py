
# ============================================================
# LeetCode 1672：最富有客户的资产总量
# 难度：Easy（简单）
# 知识点：二维列表、嵌套for循环、累计求和、最大值比较
# ============================================================

# 【题目要求】
# 给定一个二维整数数组 accounts。
#
# accounts[i] 表示第 i 位客户在不同银行的存款。
# accounts[i][j] 表示第 i 位客户在第 j 家银行的存款。
#
# 每位客户的总资产等于该客户所有银行存款之和。
#
# 要求：
# 计算每位客户的总资产，
# 找出资产最多的客户，
# 返回该客户的资产总额。
#
# 【示例1】
# 输入：accounts = [[1, 2, 3], [3, 2, 1]]
# 输出：6
#
# 解释：
# 第一位客户：1 + 2 + 3 = 6
# 第二位客户：3 + 2 + 1 = 6
# 最大资产为 6。
#
# 【示例2】
# 输入：accounts = [[1, 5], [7, 3], [3, 5]]
# 输出：10
#
# 解释：
# 第一位客户：1 + 5 = 6
# 第二位客户：7 + 3 = 10
# 第三位客户：3 + 5 = 8
# 最大资产为 10。
#
# 【示例3】
# 输入：accounts = [[2, 8, 7], [7, 1, 3], [1, 9, 5]]
# 输出：17
#
# 解释：
# 第一位客户：2 + 8 + 7 = 17
# 第二位客户：7 + 1 + 3 = 11
# 第三位客户：1 + 9 + 5 = 15
# 最大资产为 17。
#
# 【解题思路】
# 1. 创建 totala，记录目前找到的最大资产。
# 2. 外层 for 循环遍历 accounts 中的每位客户。
# 3. 每进入一位新客户，创建 totalb 并初始化为 0。
# 4. 内层 for 循环遍历该客户的所有银行存款。
# 5. 将存款累加到 totalb，得到当前客户的总资产。
# 6. 使用 max() 比较 totala 和 totalb，保留较大值。
# 7. 遍历结束后，返回 totala。
#
# 【复杂度分析】
# 假设共有 m 位客户，每位客户有 n 个银行账户：
# 时间复杂度：O(m*n)，遍历所有客户的全部存款。
# 空间复杂度：O(1)，只使用固定数量的辅助变量。
#
# ============================================================
# 自己编写的代码
# ============================================================

def maximum_wealth(accounts):
    totala = 0
    for account in accounts:
        totalb = 0
        for acc in account:
            totalb+=acc
        totala = max(totala,totalb)
    return totala


# ============================================================
# 测试代码
# ============================================================

print(maximum_wealth([[1, 2, 3], [3, 2, 1]]))
print(maximum_wealth([[1, 5], [7, 3], [3, 5]]))
print(maximum_wealth([[2, 8, 7], [7, 1, 3], [1, 9, 5]]))
