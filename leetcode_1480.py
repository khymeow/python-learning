
# ============================================================
# LeetCode 1480：一维数组的动态和
# 难度：Easy（简单）
# 知识点：列表、for循环、累计求和
# ============================================================

# 【题目要求】
# 给定一个整数数组 nums，返回数组的动态和。
#
# 动态和定义：
# result[i] = nums[0] + nums[1] + ... + nums[i]
#
# 即：结果列表中第 i 个元素，
# 等于原列表从第一个元素到当前位置的累计和。
#
# 【示例1】
# 输入：nums = [1, 2, 3, 4]
# 输出：[1, 3, 6, 10]
#
# 【示例2】
# 输入：nums = [1, 1, 1, 1, 1]
# 输出：[1, 2, 3, 4, 5]
#
# 【示例3】
# 输入：nums = [3, 1, 2, 10, 1]
# 输出：[3, 4, 6, 16, 17]
#
# 【解题思路】
# 1. 创建 total，记录当前累计和。
# 2. 创建 new，保存每一步的累计结果。
# 3. 使用 for 循环遍历 nums。
# 4. 每次将当前元素加到 total。
# 5. 把 total 添加到 new。
# 6. 返回 new。
#
# 【复杂度分析】
# 时间复杂度：O(n)，遍历列表一次。
# 空间复杂度：O(n)，创建新的结果列表。
# ============================================================


def running_sum(nums):
    total = 0
    new = []
    for num in nums:
        total += num
        new.append(total)
    return new


# ============================================================
# 测试代码
# ============================================================

print(running_sum([1, 2, 3, 4]))
print(running_sum([3, 1, 2, 10]))
print(running_sum([]))
print(running_sum([5]))
